export function getTopicsForGrade(grade, subject) {
  const level = getGradeLevel(grade);
  const levelTopics = TOPICS[level] || TOPICS.high;
  return levelTopics[subject] || TOPICS.high[subject] || TOPICS.high.other;
}

export function buildFallbackChapterContent(grade, subject, topic) {
  const gradeLabel = getGradeLabel(grade);
  const subjectLabel = getSubjectLabel(subject);
  const g = parseInt(grade, 10);

  let style = 'پاسخ را مطابق کتاب درسی و برنامه ملی بنویس.';
  if (g <= 3) {
    style = 'با جملات خیلی کوتاه و ساده مناسب دانش‌آموز ۶ تا ۹ سال بنویس. از کلمات سخت پرهیز کن.';
  } else if (g <= 6) {
    style = 'با زبان ساده و مثال‌های ملموس مناسب دبستان بنویس.';
  } else if (g <= 9) {
    style = 'با زبان متوسطه اول و مثال‌های کتاب درسی بنویس.';
  } else {
    style = 'با زبان دقیق متوسطه دوم و اصطلاحات کتاب درسی همان پایه بنویس.';
  }

  return `این بخش: ${topic} — کتاب ${subjectLabel} پایه ${gradeLabel}. ${style} فقط مطالب همین پایه را بیاور، نه مبحث پایه‌های بالاتر.`;
}

export function getTextbookTitle(grade, subject) {
  const gradeLabel = getGradeLabel(grade);
  const subjectLabel = getSubjectLabel(subject);
  const g = parseInt(grade, 10);
  if (g <= 6) return `${subjectLabel} ${gradeLabel}`;
  if (g <= 9) return `${subjectLabel} (${gradeLabel})`;
  return `${subjectLabel} — ${gradeLabel}`;
}
